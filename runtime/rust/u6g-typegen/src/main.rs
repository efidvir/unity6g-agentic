//! Usage: u6g-typegen <schemas_dir> <proto_dir> <out_dir>
//!
//! Generates the modules of the crate u6g-types (guide Section 19.2):
//! - `<out_dir>/contracts.rs`, the Rust types of every JSON Schema under `<schemas_dir>`, made by typify.
//!   The schemas are bundled first: every `$defs` entry and every root becomes one named definition, so that
//!   a type shared by several schemas is defined once; the names must therefore be unique across files.
//! - `<out_dir>/proto/`, the Protocol Buffers messages of every file under `<proto_dir>`, made by prost with
//!   the protoc of protoc-bin-vendored, so that generation needs no network and no installed protoc.

use std::collections::BTreeMap;
use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use serde_json::{Map, Value};

type Result<T> = std::result::Result<T, Box<dyn Error>>;

const HEADER: &str = "//! Generated by u6g-typegen from the JSON Schemas under schemas/. Do not edit: run make gen.\n\
#![allow(clippy::all, clippy::pedantic, unused_imports)]\n\n";

fn files_with_suffix(dir: &Path, suffix: &str) -> Result<Vec<PathBuf>> {
    let mut found = Vec::new();
    if !dir.is_dir() {
        return Ok(found);
    }
    let mut stack = vec![dir.to_path_buf()];
    while let Some(current) = stack.pop() {
        for entry in fs::read_dir(&current)? {
            let path = entry?.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.to_string_lossy().ends_with(suffix) {
                found.push(path);
            }
        }
    }
    found.sort();
    Ok(found)
}

/// The global name a reference designates: a `$defs` entry by its key, a whole schema by its title.
fn target_name(reference: &str, titles: &BTreeMap<String, String>, here: &Path) -> Result<String> {
    let (file, pointer) = reference.split_once('#').unwrap_or((reference, ""));
    if let Some(name) = pointer.strip_prefix("/$defs/") {
        if name.contains('/') {
            return Err(format!("{reference}: only references to $defs entries are supported").into());
        }
        return Ok(name.to_string());
    }
    if !pointer.is_empty() {
        return Err(format!("{reference}: only references to $defs entries are supported").into());
    }
    let resolved = normalize(&here.parent().unwrap_or(Path::new("")).join(file));
    titles
        .get(&resolved)
        .cloned()
        .ok_or_else(|| format!("{reference}: no schema at {resolved}").into())
}

fn normalize(path: &Path) -> String {
    let mut parts: Vec<String> = Vec::new();
    for part in path.components() {
        match part.as_os_str().to_string_lossy().as_ref() {
            "." | "" => {}
            ".." => {
                parts.pop();
            }
            other => parts.push(other.to_string()),
        }
    }
    parts.join("/")
}

fn rewrite_refs(value: &mut Value, titles: &BTreeMap<String, String>, here: &Path) -> Result<()> {
    match value {
        Value::Object(map) => {
            if let Some(Value::String(reference)) = map.get("$ref") {
                let name = target_name(reference, titles, here)?;
                map.insert("$ref".into(), Value::String(format!("#/definitions/{name}")));
            }
            for (_, child) in map.iter_mut() {
                rewrite_refs(child, titles, here)?;
            }
        }
        Value::Array(items) => {
            for child in items {
                rewrite_refs(child, titles, here)?;
            }
        }
        _ => {}
    }
    Ok(())
}

fn bundle(schemas: &Path, files: &[PathBuf]) -> Result<Value> {
    let mut documents = Vec::new();
    let mut titles = BTreeMap::new();
    for path in files {
        let rel = path.strip_prefix(schemas)?.to_path_buf();
        let document: Value = serde_json::from_str(&fs::read_to_string(path)?)?;
        if let Some(title) = document.get("title").and_then(Value::as_str) {
            titles.insert(normalize(&rel), title.to_string());
        }
        documents.push((rel, document));
    }
    let mut definitions = Map::new();
    let mut origin: BTreeMap<String, String> = BTreeMap::new();
    for (rel, mut document) in documents {
        rewrite_refs(&mut document, &titles, &rel)?;
        let object = document.as_object_mut().ok_or("a schema must be an object")?;
        let defs = object.remove("$defs").unwrap_or_else(|| Value::Object(Map::new()));
        let mut entries: Vec<(String, Value)> = defs.as_object().cloned().unwrap_or_default().into_iter().collect();
        if object.contains_key("type") {
            let title = object.get("title").and_then(Value::as_str).ok_or("a root schema needs a title")?.to_string();
            for key in ["$schema", "$comment", "$id", "title"] {
                object.remove(key);
            }
            entries.push((title, Value::Object(object.clone())));
        }
        for (name, schema) in entries {
            let here = rel.display().to_string();
            if let Some(first) = origin.insert(name.clone(), here.clone()) {
                return Err(format!("the name {name} is defined in {first} and in {here}; rename one").into());
            }
            definitions.insert(name, schema);
        }
    }
    let mut root = Map::new();
    root.insert("$schema".into(), Value::String("http://json-schema.org/draft-07/schema#".into()));
    root.insert("definitions".into(), Value::Object(definitions));
    Ok(Value::Object(root))
}

fn generate_contracts(schemas: &Path, out: &Path) -> Result<usize> {
    let files = files_with_suffix(schemas, ".schema.json")?;
    let target = out.join("contracts.rs");
    if files.is_empty() {
        fs::write(&target, format!("{HEADER}// No schemas yet.\n"))?;
        return Ok(0);
    }
    let bundled = bundle(schemas, &files)?;
    let root: schemars::schema::RootSchema = serde_json::from_value(bundled)?;
    let mut space = typify::TypeSpace::new(&typify::TypeSpaceSettings::default());
    space.add_root_schema(root)?;
    let tokens = space.to_stream()?;
    let file: syn::File = syn::parse2(tokens)?;
    fs::write(&target, format!("{HEADER}{}", prettyplease::unparse(&file)))?;
    Ok(files.len())
}

fn generate_proto(proto: &Path, out: &Path) -> Result<usize> {
    let files = files_with_suffix(proto, ".proto")?;
    let target = out.join("proto");
    if target.exists() {
        fs::remove_dir_all(&target)?;
    }
    fs::create_dir_all(&target)?;
    if files.is_empty() {
        fs::write(target.join("mod.rs"), "// Generated by u6g-typegen: no proto files yet.\n")?;
        return Ok(0);
    }
    let mut config = prost_build::Config::new();
    config
        .protoc_executable(protoc_bin_vendored::protoc_bin_path()?)
        .out_dir(&target)
        .include_file("mod.rs");
    config.compile_protos(&files, &[proto.to_path_buf(), protoc_bin_vendored::include_path()?])?;
    Ok(files.len())
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.len() != 3 {
        eprintln!("usage: u6g-typegen <schemas_dir> <proto_dir> <out_dir>");
        return ExitCode::from(2);
    }
    let (schemas, proto, out) = (Path::new(&args[0]), Path::new(&args[1]), Path::new(&args[2]));
    let result = generate_contracts(schemas, out).and_then(|n| Ok((n, generate_proto(proto, out)?)));
    match result {
        Ok((schemas_done, protos_done)) => {
            println!("u6g-typegen: {schemas_done} schemas -> contracts.rs, {protos_done} proto files -> proto/");
            ExitCode::SUCCESS
        }
        Err(err) => {
            eprintln!("u6g-typegen: {err}");
            ExitCode::FAILURE
        }
    }
}
